//! Shared clipboard domain types, UTI constants, and pre-check filtering logic.
//!
//! Pure Rust (no Objective-C calls) so both typed and raw backends share identical
//! filtering and instrumentation semantics.

/// Standard macOS UTIs for text and bitmap images.
pub const UTI_UTF8_PLAIN_TEXT: &str = "public.utf8-plain-text";
pub const UTI_PNG: &str = "public.png";
pub const UTI_TIFF: &str = "public.tiff";
pub const UTI_JPEG: &str = "public.jpeg";
pub const UTI_GIF: &str = "com.compuserve.gif";
pub const UTI_WEBP: &str = "org.webmproject.webp";
pub const UTI_SVG: &str = "public.svg-image";

/// Sensitive / transient / echo-guard / Universal Clipboard UTIs (AGENTS.md §3.3, threat-model.md §9.2).
pub const UTI_CONCEALED: &str = "org.nspasteboard.ConcealedType";
pub const UTI_TRANSIENT: &str = "org.nspasteboard.TransientType";
pub const UTI_AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";
pub const UTI_ONEPASSWORD: &str = "com.agilebits.onepassword";
pub const UTI_REMOTE_CLIPBOARD: &str = "com.apple.is-remote-clipboard";
pub const UTI_MYNOTE_SYNCED: &str = "dev.mynote.synced-clip";
pub const UTI_MYNOTE_VAULT_SECRET: &str = "dev.mynote.vault-secret";

/// PNG 8-byte file signature.
pub const PNG_MAGIC: [u8; 8] = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];

/// Reason a pasteboard snapshot was skipped at the `types()` pre-check stage
/// without ever reading payload bytes (`dataForType` / `stringForType`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SkipReason {
    EmptyPasteboard,
    ConcealedType,
    TransientType,
    AutoGeneratedType,
    OnePassword,
    UniversalClipboardRemote,
    SyncedByMynote,
    VaultSecret,
    UnsupportedTypes(Vec<String>),
}

/// Options controlling pre-check behavior (M4a explicit push vs M4b background watcher).
#[derive(Debug, Clone, Copy)]
pub struct ReadOptions {
    /// Default `true`: skip `com.apple.is-remote-clipboard` without calling `dataForType`,
    /// avoiding unsolicited AWDL pulls from nearby Apple devices.
    pub ignore_universal_clipboard: bool,
    /// Default `true` for M4b watcher (echo-loop guard); explicit `mynote clip push`
    /// may set `false` if user explicitly pushes a previously synced item.
    pub skip_synced_marker: bool,
}

impl Default for ReadOptions {
    fn default() -> Self {
        Self {
            ignore_universal_clipboard: true,
            skip_synced_marker: true,
        }
    }
}

/// Mechanically recorded Objective-C pasteboard API calls during a single read.
/// Used to prove `dataForType` / `stringForType` are never invoked when skipped
/// or for `public.tiff` when `public.png` is present.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct ReadStats {
    pub types_queries: usize,
    pub data_for_type_calls: Vec<String>,
    pub string_for_type_calls: Vec<String>,
}

/// Result of inspecting and optionally reading `NSPasteboard.generalPasteboard()`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ClipPayload {
    Text(String),
    Image {
        mime: &'static str,
        bytes: Vec<u8>,
        source_uti: &'static str,
        transcoded_to_png: bool,
    },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ReadOutcome {
    Payload(ClipPayload),
    Skipped(SkipReason),
}

#[derive(Debug, Clone)]
pub struct ReadReport {
    pub change_count: isize,
    pub observed_types: Vec<String>,
    pub outcome: ReadOutcome,
    pub stats: ReadStats,
}

/// Options when writing synced items back onto macOS `NSPasteboard`.
#[derive(Debug, Clone, Copy, Default)]
pub struct WriteMarkers {
    /// Attach `dev.mynote.synced-clip` (always `true` for synced items).
    pub synced_by_mynote: bool,
    /// Attach `org.nspasteboard.TransientType` + `org.nspasteboard.ConcealedType`
    /// (for `--ephemeral` sensitive items and Vault copies).
    pub ephemeral_sensitive: bool,
    /// Use `prepareForNewContentsWithOptions(CurrentHostOnly)` so macOS does not
    /// re-broadcast the item over Universal Clipboard / Handoff.
    pub current_host_only: bool,
}

/// Pure pre-check classifier executed strictly on `pb.types()` BEFORE any
/// `dataForType` / `stringForType` call.
pub fn precheck_sensitive_uti(types: &[String], opts: ReadOptions) -> Option<SkipReason> {
    if types.is_empty() {
        return Some(SkipReason::EmptyPasteboard);
    }

    // Hard-coded non-disableable privacy / password-manager markers first.
    for uti in types {
        match uti.as_str() {
            UTI_CONCEALED => return Some(SkipReason::ConcealedType),
            UTI_TRANSIENT => return Some(SkipReason::TransientType),
            UTI_AUTO_GENERATED => return Some(SkipReason::AutoGeneratedType),
            UTI_ONEPASSWORD => return Some(SkipReason::OnePassword),
            UTI_MYNOTE_VAULT_SECRET => return Some(SkipReason::VaultSecret),
            _ => {}
        }
    }

    if opts.ignore_universal_clipboard && types.iter().any(|u| u.as_str() == UTI_REMOTE_CLIPBOARD) {
        return Some(SkipReason::UniversalClipboardRemote);
    }

    if opts.skip_synced_marker && types.iter().any(|u| u.as_str() == UTI_MYNOTE_SYNCED) {
        return Some(SkipReason::SyncedByMynote);
    }

    None
}

/// Preferred content UTI selection order after passing sensitive pre-checks.
///
/// Key rule (AGENTS.md §3.3):
/// 1. Check `public.png` BEFORE `public.tiff` so macOS screenshots (which advertise
///    both 2-5 MiB PNG and 20-40 MiB uncompressed TIFF) never trigger a TIFF read.
/// 2. Check other whitelisted bitmap formats (`jpeg`, `webp`, `gif`) before TIFF.
/// 3. Fall back to `public.tiff` only when no compressed bitmap UTI exists.
/// 4. Plain UTF-8 text (`public.utf8-plain-text`). Note: `public.svg-image` is NEVER
///    selected as a bitmap image (T4 / SEC-06 XSS boundary); if plain UTF-8 text is
///    also present, it syncs as plain text.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SelectedSource {
    Png,
    Jpeg,
    Webp,
    Gif,
    TiffFallback,
    Utf8Text,
}

pub fn select_source_uti(types: &[String]) -> Option<SelectedSource> {
    let has = |target: &str| types.iter().any(|t| t.as_str() == target);

    if has(UTI_PNG) {
        Some(SelectedSource::Png)
    } else if has(UTI_JPEG) {
        Some(SelectedSource::Jpeg)
    } else if has(UTI_WEBP) {
        Some(SelectedSource::Webp)
    } else if has(UTI_GIF) {
        Some(SelectedSource::Gif)
    } else if has(UTI_TIFF) {
        Some(SelectedSource::TiffFallback)
    } else if has(UTI_UTF8_PLAIN_TEXT) {
        Some(SelectedSource::Utf8Text)
    } else {
        None
    }
}
