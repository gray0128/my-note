/// Suppresses echo loops when a clipboard write applied by `my-note` triggers a watcher event
/// within `window_ms` (default 2000 ms). For images, stores the BLAKE3 of the actual PNG bytes written.
#[derive(Clone, Debug, Default)]
pub struct EchoGuard {
    last_applied_blake3: Option<[u8; 32]>,
    applied_at_ms: u64,
}

impl EchoGuard {
    pub fn record(&mut self, blake3_hash: [u8; 32], now_ms: u64) {
        self.last_applied_blake3 = Some(blake3_hash);
        self.applied_at_ms = now_ms;
    }

    pub fn is_suppressed(&self, blake3_hash: &[u8; 32], now_ms: u64, window_ms: u64) -> bool {
        let Some(last) = self.last_applied_blake3 else {
            return false;
        };
        if &last != blake3_hash {
            return false;
        }
        now_ms.saturating_sub(self.applied_at_ms) <= window_ms
    }

    pub fn last_hash(&self) -> Option<[u8; 32]> {
        self.last_applied_blake3
    }

    pub fn applied_at_ms(&self) -> u64 {
        self.applied_at_ms
    }
}

/// In-memory undo slot capturing the previous desktop clipboard before an overwrite.
#[derive(Clone, Debug, Default)]
pub struct UndoClipboardSlot {
    previous: Option<ClipboardPayload>,
}

impl UndoClipboardSlot {
    /// Snapshot the current OS clipboard if it holds a non-sensitive readable payload.
    pub fn capture_from(&mut self, clip: &dyn SystemClipboard) {
        if let Ok(ReadClipboardResult::Payload(payload)) = clip.read() {
            self.previous = Some(payload);
        }
    }

    pub fn save(&mut self, payload: ClipboardPayload) {
        self.previous = Some(payload);
    }

    pub fn has_undo(&self) -> bool {
        self.previous.is_some()
    }

    /// Restore the previously captured payload onto `clip`. Returns `Ok(None)` if slot is empty.
    pub fn restore(&mut self, clip: &dyn SystemClipboard) -> Result<Option<WriteReceipt>, CoreError> {
        let Some(prev) = self.previous.as_ref() else {
            return Ok(None);
        };
        let receipt = clip.write(
            prev,
            ClipboardWriteOpts {
                synced_marker: true,
                sensitive: false,
                ephemeral: false,
            },
        )?;
        self.previous = None;
        Ok(Some(receipt))
    }
}

