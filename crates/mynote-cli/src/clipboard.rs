/// Default echo-suppression window (milliseconds) for M4a/M4b dual echo guard.
pub const CLIP_ECHO_WINDOW_MS: u64 = 2_000;
/// Maximum thumbnail width/height in pixels.
pub const CLIP_THUMB_MAX_DIM: u32 = 320;
/// Target upper bound for encoded thumbnails (`<= 12 KiB`, well inside `16 KiB` wire cap).
pub const CLIP_THUMB_TARGET_MAX_BYTES: usize = 12 * 1024;
/// Upper safety cap for raw macOS TIFF fallback before PNG transcode (`64 MiB`).
