/// Pure macOS `NSPasteboard.types()` pre-check: returns `Some(reason)` BEFORE any payload read
/// whenever a sensitive, transient, auto-generated, 1Password, Universal Clipboard remote,
/// Vault secret, or mynote echo-guard UTI is present.
pub fn macos_precheck_sensitive_uti(types: &[String]) -> Option<&'static str> {
    for uti in types {
        match uti.as_str() {
            UTI_CONCEALED => return Some("org.nspasteboard.ConcealedType"),
            UTI_TRANSIENT => return Some("org.nspasteboard.TransientType"),
            UTI_AUTO_GENERATED => return Some("org.nspasteboard.AutoGeneratedType"),
            UTI_ONEPASSWORD => return Some("com.agilebits.onepassword"),
            UTI_REMOTE_CLIPBOARD => return Some("com.apple.is-remote-clipboard"),
            UTI_MYNOTE_SYNCED => return Some("dev.mynote.synced-clip"),
            UTI_MYNOTE_VAULT_SECRET => return Some("dev.mynote.vault-secret"),
            _ => {}
        }
    }
    None
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MacosSelectedUti {
    Png,
    Jpeg,
    Webp,
    Gif,
    TiffFallback,
    Utf8Text,
    SvgOnlyRejected,
}

/// Pure macOS UTI selection priority (`public.png` strictly BEFORE `public.tiff`; never select SVG as image).
pub fn macos_select_source_uti(types: &[String]) -> Option<MacosSelectedUti> {
    let has = |t: &str| types.iter().any(|x| x.as_str() == t);
    if has(UTI_PNG) {
        Some(MacosSelectedUti::Png)
    } else if has(UTI_JPEG) {
        Some(MacosSelectedUti::Jpeg)
    } else if has(UTI_WEBP) {
        Some(MacosSelectedUti::Webp)
    } else if has(UTI_GIF) {
        Some(MacosSelectedUti::Gif)
    } else if has(UTI_TIFF) {
        Some(MacosSelectedUti::TiffFallback)
    } else if has(UTI_UTF8_PLAIN_TEXT) {
        Some(MacosSelectedUti::Utf8Text)
    } else if has(UTI_SVG) {
        Some(MacosSelectedUti::SvgOnlyRejected)
    } else {
        None
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum WaylandOfferChoice {
    SkipSensitive(&'static str),
    ReadImage(&'static str),
    ReadText(&'static str),
    SvgOnlyRejected,
    Empty,
}

/// Pure Wayland MIME offer classifier (`docs/spikes/s-clip-4-hyprland-wayland.md`).
pub fn wayland_classify_mimes(mimes: &[String]) -> WaylandOfferChoice {
    if mimes.is_empty() {
        return WaylandOfferChoice::Empty;
    }
    if mimes.iter().any(|m| m == MIME_KDE_PASSWORD_HINT) {
        return WaylandOfferChoice::SkipSensitive(MIME_KDE_PASSWORD_HINT);
    }
    if mimes.iter().any(|m| m == MIME_MYNOTE_VAULT_SECRET) {
        return WaylandOfferChoice::SkipSensitive(MIME_MYNOTE_VAULT_SECRET);
    }
    if mimes.iter().any(|m| m == MIME_MYNOTE_SYNCED) {
        return WaylandOfferChoice::SkipSensitive(MIME_MYNOTE_SYNCED);
    }
    for bitmap in ["image/png", "image/jpeg", "image/webp", "image/gif"] {
        if mimes.iter().any(|m| m == bitmap) {
            return WaylandOfferChoice::ReadImage(bitmap);
        }
    }
    for txt in [
        "text/plain;charset=utf-8",
        "UTF8_STRING",
        "text/plain",
        "STRING",
        "TEXT",
    ] {
        if mimes.iter().any(|m| m == txt) {
            return WaylandOfferChoice::ReadText(txt);
        }
    }
    if mimes.iter().any(|m| m == "image/svg+xml") {
        return WaylandOfferChoice::SvgOnlyRejected;
    }
    WaylandOfferChoice::Empty
}

