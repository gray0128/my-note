#[derive(Clone, Debug)]
struct StoredMockClip {
    payload: ClipboardPayload,
    opts: ClipboardWriteOpts,
    written_blake3: [u8; 32],
}

/// Thread-safe in-memory `SystemClipboard` for Daemon & unit tests (zero host pasteboard side effects).
#[derive(Debug, Default)]
pub struct InMemoryClipboard {
    inner: Mutex<Option<StoredMockClip>>,
}

impl InMemoryClipboard {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn set_user_text(&self, text: impl Into<String>) {
        let s = text.into();
        let h = *blake3::hash(s.as_bytes()).as_bytes();
        *self.inner.lock().unwrap() = Some(StoredMockClip {
            payload: ClipboardPayload::Text(s),
            opts: ClipboardWriteOpts::default(),
            written_blake3: h,
        });
    }

    pub fn snapshot(&self) -> Option<(ClipboardPayload, ClipboardWriteOpts, [u8; 32])> {
        self.inner
            .lock()
            .unwrap()
            .as_ref()
            .map(|s| (s.payload.clone(), s.opts, s.written_blake3))
    }
}

impl SystemClipboard for InMemoryClipboard {
    fn read(&self) -> Result<ReadClipboardResult, CoreError> {
        let guard = self.inner.lock().unwrap();
        let Some(entry) = guard.as_ref() else {
            return Ok(ReadClipboardResult::Empty);
        };
        if entry.opts.sensitive || entry.opts.ephemeral {
            return Ok(ReadClipboardResult::SkippedSensitive(
                "sensitive_or_ephemeral".to_string(),
            ));
        }
        if entry.opts.synced_marker {
            return Ok(ReadClipboardResult::SkippedSensitive("synced_marker".to_string()));
        }
        Ok(ReadClipboardResult::Payload(entry.payload.clone()))
    }

    fn write(&self, payload: &ClipboardPayload, opts: ClipboardWriteOpts) -> Result<WriteReceipt, CoreError> {
        let (stored_payload, written_blake3) = match payload {
            ClipboardPayload::Text(t) => {
                let h = *blake3::hash(t.as_bytes()).as_bytes();
                (ClipboardPayload::Text(t.clone()), h)
            }
            ClipboardPayload::Image { mime, bytes, .. } => {
                validate_clip_image_mime(mime)?;
                let (png, w, h_px) = transcode_to_png(bytes)?;
                let h = *blake3::hash(&png).as_bytes();
                (
                    ClipboardPayload::Image {
                        mime: "image/png".to_string(),
                        bytes: png,
                        width: Some(w),
                        height: Some(h_px),
                    },
                    h,
                )
            }
        };
        *self.inner.lock().unwrap() = Some(StoredMockClip {
            payload: stored_payload,
            opts,
            written_blake3,
        });
        Ok(WriteReceipt { written_blake3 })
    }

    fn clear(&self) -> Result<(), CoreError> {
        *self.inner.lock().unwrap() = None;
        Ok(())
    }

    fn current_mynote_blake3(&self) -> Option<[u8; 32]> {
        let guard = self.inner.lock().unwrap();
        let entry = guard.as_ref()?;
        if entry.opts.synced_marker {
            Some(entry.written_blake3)
        } else {
            None
        }
    }
}

