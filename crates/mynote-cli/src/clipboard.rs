/// Detect whether raw bytes look like an SVG XML document (strictly forbidden in image channel).
pub fn is_svg_bytes(bytes: &[u8]) -> bool {
    let prefix_len = bytes.len().min(1024);
    let Ok(head) = std::str::from_utf8(&bytes[..prefix_len]) else {
        return false;
    };
    let trimmed = head.trim_start_matches('\u{feff}').trim_start();
    let lower = trimmed.to_ascii_lowercase();
    lower.starts_with("<svg")
        || (lower.starts_with("<?xml") && lower.contains("<svg"))
        || (lower.starts_with("<!doctype svg"))
}

/// Identify a whitelisted bitmap MIME from magic bytes (and reject `.svg` / SVG bytes explicitly).
pub fn detect_image_mime_from_bytes_and_path(
    bytes: &[u8],
    path: Option<&Path>,
) -> Result<&'static str, CoreError> {
    if path
        .and_then(|p| p.extension())
        .and_then(|e| e.to_str())
        .is_some_and(|ext| ext.eq_ignore_ascii_case("svg") || ext.eq_ignore_ascii_case("svgz"))
        || is_svg_bytes(bytes)
    {
        return Err(CoreError::new(
            ErrorCode::InvalidArgument,
            "disallowed image/svg+xml payload: SVG cannot be synced as an image (XSS defense)",
            "Sync SVG markup as plain text via '--stdin' or '--text', or pass a PNG/JPEG/WebP/GIF bitmap",
        ));
    }
    if bytes.len() >= 8 && bytes[..8] == PNG_MAGIC {
        return Ok("image/png");
    }
    if bytes.len() >= 3 && bytes[0] == 0xFF && bytes[1] == 0xD8 && bytes[2] == 0xFF {
        return Ok("image/jpeg");
    }
    if bytes.len() >= 12 && &bytes[0..4] == b"RIFF" && &bytes[8..12] == b"WEBP" {
        return Ok("image/webp");
    }
    if bytes.len() >= 6 && (&bytes[0..6] == b"GIF87a" || &bytes[0..6] == b"GIF89a") {
        return Ok("image/gif");
    }
    Err(CoreError::new(
        ErrorCode::InvalidArgument,
        "unsupported image format (only image/png, image/jpeg, image/webp, image/gif are allowed)",
        "Convert the file to PNG, JPEG, WebP, or GIF (<= 10 MiB)",
    ))
}

/// Inspect `(width, height)` from encoded bitmap bytes without full pixel decoding when possible.
pub fn inspect_image_dimensions(bytes: &[u8]) -> Option<(u32, u32)> {
    if is_svg_bytes(bytes) {
        return None;
    }
    ImageReader::new(Cursor::new(bytes))
        .with_guessed_format()
        .ok()?
        .into_dimensions()
        .ok()
}

/// Transcode any supported bitmap (`png`, `jpeg`, `webp`, `gif`, `tiff`) into valid PNG bytes
/// and return `(png_bytes, width, height)`. Rejects SVG and payloads whose output exceeds 10 MiB.
pub fn transcode_to_png(bytes: &[u8]) -> Result<(Vec<u8>, u32, u32), CoreError> {
    if bytes.is_empty() {
        return Err(CoreError::new(
            ErrorCode::InvalidArgument,
            "cannot transcode empty image payload",
            "Provide a valid PNG/JPEG/WebP/GIF/TIFF image",
        ));
    }
    if is_svg_bytes(bytes) {
        return Err(CoreError::new(
            ErrorCode::InvalidArgument,
            "disallowed image/svg+xml payload cannot be transcoded as bitmap",
            "Sync SVG as plain text instead",
        ));
    }
    if bytes.len() > MAX_RAW_TIFF_BYTES {
        return Err(CoreError::new(
            ErrorCode::InvalidArgument,
            format!("raw image payload {} bytes exceeds safety cap", bytes.len()),
            "Provide an image <= 10 MiB",
        ));
    }
    let reader = ImageReader::new(Cursor::new(bytes))
        .with_guessed_format()
        .map_err(|e| {
            CoreError::new(
                ErrorCode::InvalidArgument,
                format!("cannot detect image format: {e}"),
                "Provide a valid PNG, JPEG, WebP, GIF, or TIFF image",
            )
        })?;
    let fmt = reader.format().ok_or_else(|| {
        CoreError::new(
            ErrorCode::InvalidArgument,
            "unrecognized bitmap image format",
            "Provide a valid PNG, JPEG, WebP, GIF, or TIFF image",
        )
    })?;
    if !matches!(
        fmt,
        ImageFormat::Png | ImageFormat::Jpeg | ImageFormat::WebP | ImageFormat::Gif | ImageFormat::Tiff
    ) {
        return Err(CoreError::new(
            ErrorCode::InvalidArgument,
            format!("disallowed image format {fmt:?}"),
            "Only PNG, JPEG, WebP, GIF (and macOS TIFF fallback) are supported",
        ));
    }
    let img = reader.decode().map_err(|e| {
        CoreError::new(
            ErrorCode::InvalidArgument,
            format!("failed decoding {fmt:?} image: {e}"),
            "Verify the image file is not corrupted",
        )
    })?;
    let (w, h) = (img.width(), img.height());
    if fmt == ImageFormat::Png && bytes.len() <= CLIP_BLOB_MAX_BYTES {
        return Ok((bytes.to_vec(), w, h));
    }
    let mut out = Vec::new();
    img.write_to(&mut Cursor::new(&mut out), ImageFormat::Png)
        .map_err(|e| {
            CoreError::new(
                ErrorCode::IntegrityError,
                format!("failed encoding PNG: {e}"),
                "Retry with a valid bitmap image",
            )
        })?;
    if out.len() > CLIP_BLOB_MAX_BYTES {
        return Err(CoreError::new(
            ErrorCode::InvalidArgument,
            format!(
                "transcoded PNG ({} bytes) exceeds 10 MiB limit ({CLIP_BLOB_MAX_BYTES} bytes)",
                out.len()
            ),
            "Resize or compress the image under 10 MiB before pushing",
        ));
    }
    Ok((out, w, h))
}

/// Generate a compact thumbnail (`<= 320px`, `<= 12 KiB`) for `ClipMetaV1.blob.thumb_*`.
/// Converts RGBA images to RGB8 before JPEG encoding so alpha screenshots never fail.
pub fn make_thumbnail(bytes: &[u8], mime: &str) -> Option<(String, Vec<u8>)> {
    validate_clip_image_mime(mime).ok()?;
    if is_svg_bytes(bytes) || bytes.len() > CLIP_BLOB_MAX_BYTES {
        return None;
    }
    let img = image::load_from_memory(bytes).ok()?;
    for &(dim, quality) in &[(CLIP_THUMB_MAX_DIM, 78u8), (240, 62), (160, 50), (120, 42)] {
        let resized = img.thumbnail(dim, dim);
        let rgb = resized.to_rgb8();
        let mut out = Vec::new();
        let mut enc = JpegEncoder::new_with_quality(&mut out, quality);
        if enc.encode_image(&rgb).is_ok()
            && out.len() <= CLIP_THUMB_TARGET_MAX_BYTES
            && out.len() <= CLIP_THUMB_MAX_BYTES
        {
            return Some(("image/jpeg".to_string(), out));
        }
    }
    None
}

/// Validate raw `"PNG"` clipboard bytes: reject SVG spoofing, enforce 10 MiB ceiling, and inspect `(width, height)`.
pub fn validate_png_clipboard_bytes(bytes: &[u8]) -> Result<(u32, u32), CoreError> {
    if bytes.is_empty() {
        return Err(CoreError::new(
            ErrorCode::InvalidArgument,
            "clipboard PNG payload is empty",
            "Copy a non-empty PNG/JPEG/WebP/GIF bitmap",
        ));
    }
    if is_svg_bytes(bytes) {
        return Err(CoreError::new(
            ErrorCode::InvalidArgument,
            "disallowed image/svg+xml payload disguised inside PNG clipboard format",
            "Sync SVG markup as plain text instead of an image",
        ));
    }
    if bytes.len() > CLIP_BLOB_MAX_BYTES {
        return Err(CoreError::new(
            ErrorCode::InvalidArgument,
            format!("clipboard PNG ({} bytes) exceeds 10 MiB limit", bytes.len()),
            "Resize or compress the image under 10 MiB",
        ));
    }
    if bytes.len() < 8 || bytes[..8] != PNG_MAGIC {
        return Err(CoreError::new(
            ErrorCode::InvalidArgument,
            "clipboard PNG payload missing 8-byte PNG signature",
            "Copy a valid PNG bitmap",
        ));
    }
    ImageReader::with_format(Cursor::new(bytes), ImageFormat::Png)
        .into_dimensions()
        .map_err(|e| {
            CoreError::new(
                ErrorCode::InvalidArgument,
                format!("invalid clipboard PNG header dimensions: {e}"),
                "Copy a valid PNG bitmap",
            )
        })
}

/// Build a standard Win32 `CF_DIBV5` (`BITMAPV5HEADER`, 124-byte header, bottom-up 32-bpp BGRA)
/// byte buffer from an RGBA8 image.
pub fn rgba_to_dibv5_bytes(width: u32, height: u32, rgba: &[u8]) -> Vec<u8> {
    assert_eq!(rgba.len(), (width as usize) * (height as usize) * 4);
    let header_size = 124usize;
    let pixel_bytes = (width as usize) * (height as usize) * 4;
    let mut out = vec![0u8; header_size + pixel_bytes];

    out[0..4].copy_from_slice(&(header_size as u32).to_le_bytes());
    out[4..8].copy_from_slice(&(width as i32).to_le_bytes());
    out[8..12].copy_from_slice(&(height as i32).to_le_bytes());
    out[12..14].copy_from_slice(&1u16.to_le_bytes());
    out[14..16].copy_from_slice(&32u16.to_le_bytes());
    out[16..20].copy_from_slice(&WIN_BI_BITFIELDS.to_le_bytes());
    out[20..24].copy_from_slice(&(pixel_bytes as u32).to_le_bytes());
    out[40..44].copy_from_slice(&0x00FF_0000u32.to_le_bytes());
    out[44..48].copy_from_slice(&0x0000_FF00u32.to_le_bytes());
    out[48..52].copy_from_slice(&0x0000_00FFu32.to_le_bytes());
    out[52..56].copy_from_slice(&0xFF00_0000u32.to_le_bytes());
    out[56..60].copy_from_slice(&0x7352_4742u32.to_le_bytes());

    let row_bytes = (width as usize) * 4;
    for y in 0..(height as usize) {
        let src_row = (height as usize - 1 - y) * row_bytes;
        let dst_row = header_size + y * row_bytes;
        for x in 0..(width as usize) {
            let s = src_row + x * 4;
            let d = dst_row + x * 4;
            out[d] = rgba[s + 2];
            out[d + 1] = rgba[s + 1];
            out[d + 2] = rgba[s];
            out[d + 3] = rgba[s + 3];
        }
    }
    out
}

