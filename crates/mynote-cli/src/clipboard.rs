#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ClipboardPayload {
    Text(String),
    Image {
        mime: String,
        bytes: Vec<u8>,
        width: Option<u32>,
        height: Option<u32>,
    },
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct ClipboardWriteOpts {
    pub synced_marker: bool,
    pub sensitive: bool,
    pub ephemeral: bool,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ReadClipboardResult {
    Payload(ClipboardPayload),
    Empty,
    SkippedSensitive(String),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct WriteReceipt {
    /// BLAKE3 of the exact bytes written to the OS clipboard (transcoded PNG bytes for images,
    /// UTF-8 bytes for text).
    pub written_blake3: [u8; 32],
}

pub trait SystemClipboard: Send + Sync {
    fn read(&self) -> Result<ReadClipboardResult, CoreError>;
    fn write(&self, payload: &ClipboardPayload, opts: ClipboardWriteOpts) -> Result<WriteReceipt, CoreError>;
    fn clear(&self) -> Result<(), CoreError>;
    /// Inspect ONLY a mynote-marked clipboard item's raw BLAKE3 digest for safe ephemeral auto-clear.
    /// Returns `None` if the user has overwritten the clipboard with a non-mynote item (without reading user data).
    fn current_mynote_blake3(&self) -> Option<[u8; 32]>;
    /// Returns `true` only for the live OS pasteboard adapter (`NativeSystemClipboard`).
    /// Mock/file clipboards return `false` so hermetic tests never attach background watchers to the host OS clipboard.
    fn is_native(&self) -> bool {
        false
    }
}

